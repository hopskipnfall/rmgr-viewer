const FTILT_RANGE: [number, number] = [0x0c1, 0x0c5];
const FSMASH_RANGE: [number, number] = [0x0ca, 0x0ce];

export function actionStateName(id: number): string {
  const known = ACTION_STATE_NAMES[id];
  if (known) return known;
  if (id >= FTILT_RANGE[0] && id <= FTILT_RANGE[1]) return "FTilt";
  if (id >= FSMASH_RANGE[0] && id <= FSMASH_RANGE[1]) return "FSmash";
  if (id >= 0x0dc) return `Special 0x${id.toString(16)}`;
  return `State 0x${id.toString(16)}`;
}
